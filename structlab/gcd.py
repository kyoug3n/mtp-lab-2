"""Средн. 4: наибольший общий делитель (НОД) двух целых чисел.

Используется алгоритм Евклида с остатком от деления. Исходная формулировка
алгоритма — вычитание меньшего числа из большего — делает те же шаги, но по
одному вычитанию за раз: остаток ``a % b`` заменяет сразу все вычитания ``b``
из ``a``. При сильно различающихся числах разница огромна: для НОД(10**18, 1)
вычитаний понадобилось бы 10**18 - 1, а деление с остатком — одно.
"""
from structlab.console import InputFunc, OutputFunc, read_int


def gcd(a: int, b: int) -> int:
    """Найти НОД двух целых чисел алгоритмом Евклида.

    Знаки чисел на результат не влияют, НОД всегда неотрицателен;
    ``gcd(0, 0) == 0``, как у ``math.gcd``. Число шагов цикла растёт как
    логарифм меньшего из чисел (теорема Ламе), поэтому функция быстро
    работает и с очень большими целыми числами.

    :raises TypeError: если аргументы не целые числа. ``bool`` в Python —
        подкласс ``int`` (``math.gcd(True, 6)`` вернёт 1), но здесь
        логические значения тоже отклоняются как не числа.
    """
    for value in (a, b):
        if isinstance(value, bool) or not isinstance(value, int):
            raise TypeError("НОД определён только для целых чисел")
    a, b = abs(a), abs(b)
    while b != 0:
        a, b = b, a % b
    return a


def run(
    input_func: InputFunc = input, output_func: OutputFunc = print
) -> None:
    """Запросить два целых числа и вывести их НОД."""
    output_func("НОД двух целых чисел («выход» — завершить).")
    a = read_int("Первое число: ", input_func, output_func)
    if a is None:
        return
    b = read_int("Второе число: ", input_func, output_func)
    if b is None:
        return
    output_func(f"НОД({a}, {b}) = {gcd(a, b)}")


if __name__ == "__main__":
    run()
